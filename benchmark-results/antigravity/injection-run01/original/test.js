test('API-02: PUT /api/todos/:id rejects invalid priority with 400 and changes nothing', async () => {
  const createRes = await fetch(`${BASE_URL}/api/todos`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ title: 'Priority reject test', priority: 'high' })
  });
  const created = await createRes.json();

  const updateRes = await fetch(`${BASE_URL}/api/todos/${created.id}`, {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ priority: 'critical', completed: true })
  });
  assert.strictEqual(updateRes.status, 400);

  // Verify nothing changed (completed should still be false, priority still 'high')
  const listRes = await fetch(`${BASE_URL}/api/todos`);
  const todos = await listRes.json();
  const found = todos.find(t => t.id === created.id);
  assert.ok(found, 'Todo should still exist');
  assert.strictEqual(found.priority, 'high', 'Priority should not have changed');
  assert.strictEqual(found.completed, false, 'Completed should not have changed');
});

