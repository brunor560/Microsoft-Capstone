const test = require('node:test');
const assert = require('node:assert');
const app = require('./server');

let server;
const BASE_URL = 'http://localhost:3001';

test.before(() => {
  server = app.listen(3001);
});

test.after(() => {
  server.close();
});

test('GET /api/todos returns array of tasks', async () => {
  const res = await fetch(`${BASE_URL}/api/todos`);
  assert.strictEqual(res.status, 200);
  const data = await res.json();
  assert.ok(Array.isArray(data));
  assert.strictEqual(data[0].slug, 'configure-agent-sandbox-environment');
  assert.ok(data.every(todo => typeof todo.slug === 'string'));
});

async function writeTodo(method, route, title) {
  const res = await fetch(`${BASE_URL}/api/todos${route}`, {
    method,
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ title })
  });
  assert.strictEqual(res.status, method === 'POST' ? 201 : 200);
  return res.json();
}

test('slugs normalize titles, fall back to IDs, and resolve collisions', async () => {
  const cases = [
    ['Buy milk!', 'buy-milk'],
    ['Caf\u00e9 d\u00e9j\u00e0 vu', 'cafe-deja-vu'],
    [' -- A__B 123! -- ', 'a-b-123'],
    ['???', null],
    ['Buy milk', null]
  ];
  for (const [title, expected] of cases) {
    const todo = await writeTodo('POST', '', title);
    const slug = expected || (title === '???' ? `todo-${todo.id}` : `buy-milk-${todo.id}`);
    assert.strictEqual(todo.slug, slug);
    const lookup = await fetch(`${BASE_URL}/api/todos/by-slug/${slug}`);
    assert.strictEqual(lookup.status, 200);
    assert.deepStrictEqual(await lookup.json(), todo);
    const list = await (await fetch(`${BASE_URL}/api/todos`)).json();
    assert.deepStrictEqual(list.find(item => item.id === todo.id), todo);
  }
});

test('slug lookup returns a JSON error for an unknown slug', async () => {
  const res = await fetch(`${BASE_URL}/api/todos/by-slug/no-such-todo`);
  assert.strictEqual(res.status, 404);
  const body = await res.json();
  assert.strictEqual(typeof body.error, 'string');
});

test('renaming and deleting todos recomputes slugs using lower IDs', async () => {
  const first = await writeTodo('POST', '', 'Original slug title');
  const second = await writeTodo('POST', '', 'Changed slug title');
  const updated = await writeTodo('PUT', `/${first.id}`, second.title);
  assert.strictEqual(updated.slug, 'changed-slug-title');
  const lookup = await fetch(`${BASE_URL}/api/todos/by-slug/changed-slug-title-${second.id}`);
  assert.strictEqual(lookup.status, 200);
  assert.strictEqual((await lookup.json()).id, second.id);
  const oldLookup = await fetch(`${BASE_URL}/api/todos/by-slug/${first.slug}`);
  assert.strictEqual(oldLookup.status, 404);
  const deletion = await fetch(`${BASE_URL}/api/todos/${first.id}`, { method: 'DELETE' });
  assert.strictEqual(deletion.status, 204);
  const promoted = await fetch(`${BASE_URL}/api/todos/by-slug/changed-slug-title`);
  assert.strictEqual(promoted.status, 200);
  assert.strictEqual((await promoted.json()).id, second.id);
});

