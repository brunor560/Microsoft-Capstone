"""Generate readable Markdown from the authoritative JSON dataset.

Outputs go to <dataset>/out/ with a "generated, do not edit" header. They are
review artifacts, not a publication: no score, rank or combined view.
"""
import os

from . import model
from . import review
from .render_cell import cell_md
from .render_cells import BANNER, esc, matrix_md, reviews_md, validation_md

HEAD = ('<!-- Generated by `python3 -m tools.approach_a render` from %s. Do not edit; '
        'change the JSON and regenerate. -->\n\n')


def write(store, name, text, src):
    p = store.path('out', name)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8') as f:
        f.write(HEAD % src + text)
    return p


def manifest_md(manifest, people):
    a = manifest.get('approval')
    n = len(manifest['profiles'])
    out = ['# Assessment manifest\n', BANNER,
           'Manifest version: **%s**. Profiles (P): **%d**. Expected cells (18 x P): **%d**.\n' % (
               manifest.get('manifest_version'), n, 18 * n)]
    if a:
        out.append('Approval: **approved** by %s on %s (manifest SHA-256 `%s`).\n' % (
            people.get(a['approver'], {}).get('name', a['approver']), a['approved_at'], a['manifest_sha256'][:16]))
    else:
        out.append('Approval: **not approved**. No cell is accepted until an approver approves this version.\n')
    for p in manifest['profiles']:
        v = p.get('version') or {}
        who = people.get(p.get('confirmed_by'), {}).get('name', p.get('confirmed_by'))
        rows = [('Tool / surface', '%s / %s' % (p['tool'], p['surface_label'])),
                ('Category tags', ', '.join('MATRIX:' + t for t in p.get('category_tags', []))),
                ('Version', '%s (%s)' % (v.get('value') or 'unversioned', v.get('kind', ''))),
                ('Documentation versioning', v.get('documentation_note', '')),
                ('Modes', '; '.join(p.get('modes', []))),
                ('Platforms', '; '.join(p.get('platforms', []))),
                ('Account and tier', p.get('account_and_tier')),
                ('Interface and execution', p.get('interface_and_execution_location')),
                ('Included components', '; '.join(p.get('included_components', []))),
                ('Exclusions', '; '.join(p.get('exclusions', []))),
                ('Instructions and permissions', p.get('instructions_and_permissions')),
                ('Documentation base', p.get('documentation_base')),
                ('Source access date', p.get('source_access_date')),
                ('Boundary confirmed by', '%s at %s' % (who, p.get('confirmed_at')))]
        out += ['\n## %s\n' % p['id'], '| Field | Value |', '| --- | --- |']
        out += ['| %s | %s |' % (k, esc(val)) for k, val in rows]
    return '\n'.join(out) + '\n'


def sources_md(data):
    out = ['# Official-source index\n', BANNER,
           'Shared by all profiles. Each entry is a short verbatim quote checked against the cited section of a '
           'cached copy of the page. The check confirms where the text is, not that the claim is right.\n',
           '\n## Evidence entries\n',
           '| ID | Page | Section | Surface | Access date | Version or update | Check | Quote |',
           '| --- | --- | --- | --- | --- | --- | --- | --- |']
    for eid in sorted(data['entries'], key=lambda e: int(e[1:])):
        e = data['entries'][eid]
        out.append('| MATRIX:%s | [%s](%s) | %s | %s | %s | %s | %s | "%s" |' % (
            eid, esc(e['page_title']), e['url'], esc(e['section']), esc(e['surface']), e['access_date'],
            esc(e['version_or_update']), e['check'], esc(e['quote'])))
    out += ['\n## Pages reviewed\n', '| URL | Title | Publisher | Available on | Access date | Status | SHA-256 |',
            '| --- | --- | --- | --- | --- | --- | --- |']
    for url in sorted(data['pages']):
        p = data['pages'][url]
        out.append('| %s | %s | %s | %s | %s | %s | `%s` |' % (
            url, esc(p.get('title')), esc(p.get('publisher')), ', '.join(p.get('available_on') or []) or '-',
            p.get('access_date', '-'), p.get('status'), (p.get('sha256') or '')[:12]))
    return '\n'.join(out) + '\n'


def worklog_md(entries):
    out = ['# Assessment work log\n',
           'Append-only record from `worklog.jsonl`. Agent activity is labeled. This workbench fetches official '
           'documentation pages only: it does not install or run any assessed developer tool and makes no model API '
           'calls (SRS Spec 5.4).\n',
           '| Time (UTC) | Actor | Event | Details |', '| --- | --- | --- | --- |']
    for e in entries:
        d = {k: v for k, v in e.items() if k not in ('ts', 'actor', 'event')}
        out.append('| %s | %s | %s | %s |' % (e['ts'], esc(e['actor']), e['event'], esc(d)))
    return '\n'.join(out) + '\n'


def run(store):
    cat, manifest = store.catalog(), store.load('manifest.json')
    cells, people = store.load('cells.json')['cells'], store.people()
    sources, current = store.load('sources.json'), review.current(store, cells)
    written = [
        write(store, 'manifest.md', manifest_md(manifest, people), 'manifest.json'),
        write(store, 'matrix.md', matrix_md(cat, manifest, cells, current), 'cells.json'),
        write(store, 'sources.md', sources_md(sources), 'sources.json'),
        write(store, 'worklog.md', worklog_md(store.worklog()), 'worklog.jsonl'),
        write(store, 'reviews.md', reviews_md(store.load('reviews.json')['reviews'], cells, current, people),
              'reviews.json'),
    ]
    for p in manifest['profiles']:
        for f in cat['features']:
            cid = model.cell_id(f['id'], p['id'])
            if cid in cells:
                written.append(write(store, os.path.join('cells', p['id'], f['id'] + '.md'),
                                     cell_md(f, p, cells[cid], sources, people, current.get(cid)), 'cells.json'))
    if store.exists('validation_report.json'):
        written.append(write(store, 'validation_report.md',
                             validation_md(store.load('validation_report.json')), 'validation_report.json'))
    store.log('rendered', files=len(written))
    return written

